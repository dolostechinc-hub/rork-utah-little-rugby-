DO $$
DECLARE
  v_inserted int;
  v_with_photo int;
  v_age_verified int;
  v_match_exact int;
  v_match_club_diff int;
  v_new int;
BEGIN
  SELECT count(*),
         count(*) FILTER (WHERE photo_uri IS NOT NULL AND photo_uri <> ''),
         count(*) FILTER (WHERE is_age_verified)
    INTO v_inserted, v_with_photo, v_age_verified
  FROM public.roster_players
  WHERE org_id = '553f476b-d0f1-4f3c-aa63-90bc3be42d36';

  -- Re-derive the import classification by joining to the existing org.
  WITH new_rows AS (
    SELECT first_name, last_name, date_of_birth, club
    FROM public.roster_players
    WHERE org_id = '553f476b-d0f1-4f3c-aa63-90bc3be42d36'
  ),
  ex AS (
    SELECT
      lower(regexp_replace(unaccent(first_name), '[^a-zA-Z]', '', 'g')) AS fn_n,
      lower(regexp_replace(unaccent(last_name),  '[^a-zA-Z]', '', 'g')) AS ln_n,
      date_of_birth, club
    FROM public.roster_players
    WHERE org_id = '296fbc1a-0bec-4599-8b52-53191fb7879f'
  )
  SELECT
    count(*) FILTER (WHERE e.fn_n IS NOT NULL AND lower(e.club) = lower(n.club)) AS match_exact,
    count(*) FILTER (WHERE e.fn_n IS NOT NULL AND lower(e.club) <> lower(n.club)) AS match_club_diff,
    count(*) FILTER (WHERE e.fn_n IS NULL) AS as_new
    INTO v_match_exact, v_match_club_diff, v_new
  FROM new_rows n
  LEFT JOIN LATERAL (
    SELECT *
    FROM ex
    WHERE ex.fn_n = lower(regexp_replace(unaccent(n.first_name), '[^a-zA-Z]', '', 'g'))
      AND ex.ln_n = lower(regexp_replace(unaccent(n.last_name),  '[^a-zA-Z]', '', 'g'))
      AND ex.date_of_birth = n.date_of_birth
    LIMIT 1
  ) e ON true;

  RAISE NOTICE
    '[041] DONE. inserted=% match_exact=% match_club_diff=% as_new=% with_photo=% age_verified=%',
    v_inserted, v_match_exact, v_match_club_diff, v_new, v_with_photo, v_age_verified;

  IF v_inserted <> 1563 THEN
    RAISE EXCEPTION
      '[041] expected to insert exactly 1563 rows but inserted %; rolling back',
      v_inserted;
  END IF;
END $$;

